// Generates a 64x64 blue-noise threshold tile with the void-and-cluster
// method (Ulichney 1993) and writes it as base64 into
// packages/shaders/src/primitives/dither-pattern/blue-noise-tile.ts.
// Deterministic (seeded PRNG), so re-running reproduces the same tile.
import { writeFileSync } from 'node:fs';

const SIZE = 64;
const COUNT = SIZE * SIZE;
const SIGMA = 1.9;

// Seeded PRNG (mulberry32) — reproducible builds, no Math.random.
function mulberry32(seed) {
  let state = seed;

  return () => {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);

    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;

    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Toroidal gaussian kernel, precomputed per wrapped offset.
const kernel = new Float64Array(COUNT);

for (let y = 0; y < SIZE; y++) {
  for (let x = 0; x < SIZE; x++) {
    const dx = Math.min(x, SIZE - x);
    const dy = Math.min(y, SIZE - y);

    kernel[y * SIZE + x] = Math.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA));
  }
}

// energy[i] = sum of kernel contributions from every set point; updated
// incrementally as points toggle.
const energy = new Float64Array(COUNT);

function toggle(index, sign) {
  const px = index % SIZE;
  const py = (index / SIZE) | 0;

  for (let y = 0; y < SIZE; y++) {
    const wrappedY = (y - py + SIZE) % SIZE;

    for (let x = 0; x < SIZE; x++) {
      const wrappedX = (x - px + SIZE) % SIZE;

      energy[y * SIZE + x] += sign * kernel[wrappedY * SIZE + wrappedX];
    }
  }
}

// Find the tightest cluster (max energy among set cells) or largest void
// (min energy among unset cells).
function extreme(pattern, wantSet, pick) {
  let best = -1;
  let bestEnergy = pick === 'max' ? -Infinity : Infinity;

  for (let i = 0; i < COUNT; i++) {
    if (pattern[i] !== wantSet) continue;
    const better = pick === 'max' ? energy[i] > bestEnergy : energy[i] < bestEnergy;

    if (better) {
      bestEnergy = energy[i];
      best = i;
    }
  }

  return best;
}

// Phase 0: seed ~10% random minority points, then relax swaps until the
// tightest cluster and the largest void are the same cell (stable).
const random = mulberry32(0x4d415438);
const pattern = new Uint8Array(COUNT);
// Integer, or the fractional bound ripples through every phase: one seed
// escapes phase 1 unranked (rank -1 -> threshold 255) and phase 2 runs one
// extra iteration against an already-full tile.
const seedCount = Math.floor(COUNT / 10);
let placed = 0;

while (placed < seedCount) {
  const index = (random() * COUNT) | 0;

  if (pattern[index]) continue;
  pattern[index] = 1;
  toggle(index, +1);
  placed += 1;
}
for (;;) {
  const cluster = extreme(pattern, 1, 'max');

  pattern[cluster] = 0;
  toggle(cluster, -1);
  const voidCell = extreme(pattern, 0, 'min');

  pattern[voidCell] = 1;
  toggle(voidCell, +1);
  if (voidCell === cluster) break;
}

const rank = new Int32Array(COUNT).fill(-1);

// Phase 1: rank the seed points by removing tightest clusters down to zero.
const phase1 = Uint8Array.from(pattern);
let currentRank = seedCount - 1;

while (currentRank >= 0) {
  const cluster = extreme(phase1, 1, 'max');

  phase1[cluster] = 0;
  toggle(cluster, -1);
  rank[cluster] = currentRank;
  currentRank -= 1;
}

// Rebuild energy for the original seed pattern, then phases 2+3: insert at
// the largest void until the tile is full.
energy.fill(0);
for (let i = 0; i < COUNT; i++) if (pattern[i]) toggle(i, +1);
for (let insertRank = seedCount; insertRank < COUNT; insertRank++) {
  const voidCell = extreme(pattern, 0, 'min');

  pattern[voidCell] = 1;
  toggle(voidCell, +1);
  rank[voidCell] = insertRank;
}

// Ranks 0..4095 -> bytes 0..255, each value exactly 16 times.
const bytes = Uint8Array.from(rank, (value) => value >> 4);
const base64 = Buffer.from(bytes).toString('base64');
const output = `// Generated by scripts/generate-blue-noise.mjs — do not edit by hand.
// A 64x64 blue-noise threshold tile (void-and-cluster): thresholds are
// evenly distributed in value but spatially clump-free, which is what makes
// blue-noise dithering read as organic texture instead of grid or static.

export const BLUE_NOISE_SIZE = 64;

export const BLUE_NOISE_TILE: Uint8Array<ArrayBuffer> = Uint8Array.from(
  atob('${base64}'),
  (character) => character.charCodeAt(0),
);
`;

writeFileSync(
  new URL('../packages/shaders/src/primitives/dither-pattern/blue-noise-tile.ts', import.meta.url),
  output,
);
console.log('blue-noise-tile.ts written');
